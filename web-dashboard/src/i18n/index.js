export function resolveLocale(preferred) {
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('afrikoba_lang') : null;
  const candidate = preferred || stored || 'sw';
  const pick = (v) => (v && typeof v === 'string' && (v.toLowerCase().startsWith('en') ? 'en' : v.toLowerCase().startsWith('sw') ? 'sw' : null));
  return pick(candidate) || 'sw';
}

export function tr(key, locale = 'sw', vars = {}) {
  const table = messages[locale] || messages.sw;
  let text = table[key];
  if (text === undefined) {
    const fallback = messages.sw[key];
    text = fallback !== undefined ? fallback : key;
  }
  return Object.entries(vars).reduce((str, [k, v]) => str.split(`{${k}}`).join(String(v)), text);
}

